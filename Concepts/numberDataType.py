'''
In Python Data Type of a Variable id determined based on the value it has.
In Python The Numeric Value Of a Variable can be Integer , Floating point , Complex Numbers .
'''
#Integer Value Can be positive or Negative and can have any length.
integerVar1=12
integerVar2=-24
integerVar3=123456789

#Floating Point Value Can also be Positive or Negative .
floatingVar1=1.0
floatingVar2=-1.0

#Complex Value like a+bj can also be represented . where a is the real part and b is the imaginary part . In python we Use j not i in the imaginary part
complexVar=3+5j
print(complexVar.real) #gives the real part 3.0
print(complexVar.imag) #gives the Complex part 5.0

